/* 农历 1900 年正月初一 = 公历 1900-01-31 */
const LUNAR_BASE = Date.UTC(1900, 0, 31);

const STEMS = '甲乙丙丁戊己庚辛壬癸';
const BRANCHES = '子丑寅卯辰巳午未申酉戌亥';
const MONTH_NAMES = ['正月', '二月', '三月', '四月', '五月', '六月', '七月', '八月', '九月', '十月', '冬月', '腊月'];
const DAY_NAMES = [
  '初一', '初二', '初三', '初四', '初五', '初六', '初七', '初八', '初九', '初十',
  '十一', '十二', '十三', '十四', '十五', '十六', '十七', '十八', '十九', '二十',
  '廿一', '廿二', '廿三', '廿四', '廿五', '廿六', '廿七', '廿八', '廿九', '三十',
];

/** 公历日期 → 农历 {year, month, day, isLeap}；越界返回 null */
export function solarToLunar(date) {
  const days = Math.floor((Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) - LUNAR_BASE) / 86400000);
  if (days < 0) return null;
  let y = 0;
  let rest = days;
  while (y < LUNAR_YEARS.length) {
    const info = LUNAR_YEARS[y];
    let total = 0;
    for (let i = 1; i <= 12; i++) total += info[i];
    if (info[0]) total += info[13];
    if (rest < total) break;
    rest -= total;
    y++;
  }
  if (y >= LUNAR_YEARS.length) return null;
  const info = LUNAR_YEARS[y];
  const leap = info[0];
  let month = 1, isLeap = false, day = 1;
  for (let m = 1; m <= 12; m++) {
    const d = info[m];
    if (rest < d) { month = m; isLeap = false; day = rest + 1; break; }
    rest -= d;
    if (leap === m) {
      const ld = info[13];
      if (rest < ld) { month = m; isLeap = true; day = rest + 1; break; }
      rest -= ld;
    }
  }
  return { year: 1900 + y, month, day, isLeap };
}

/** 干支纪年（如 乙巳） */
export function ganzhi(year) {
  return STEMS[(year - 4) % 10] + BRANCHES[(year - 4) % 12];
}

/** 完整农历字符串：乙巳年闰六月十九 */
export function lunarText(date) {
  const l = solarToLunar(date);
  if (!l) return '';
  const y = ganzhi(l.year) + '年';
  const m = (l.isLeap ? '闰' : '') + MONTH_NAMES[l.month - 1];
  const d = DAY_NAMES[l.day - 1];
  return y + m + d;
}
